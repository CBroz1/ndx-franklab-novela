@pytest.fixture
def written_nwb_path(tmp_path, all_types_nwbfile):
    """Write the all-types file to disk and return its path.

    Parameters
    ----------
    tmp_path : pathlib.Path
        pytest-provided temporary directory.
    all_types_nwbfile : pynwb.NWBFile
        File to write.

    Returns
    -------
    pathlib.Path
        Path of the written NWB file.
    """
    path = tmp_path / "all_types.nwb"
    with NWBHDF5IO(str(path), mode="w") as io:
        io.write(all_types_nwbfile)
    return path


@pytest.fixture
def baseline_fixture_dir():
    """Return the directory of pre-migration fixture files.

    Returns
    -------
    pathlib.Path
        Directory holding the archived NWB fixtures.

    Notes
    -----
    Skips the requesting test when the directory is absent, so a checkout
    without the fixtures still runs the rest of the suite.
    """
    if not BASELINE_FIXTURE_DIR.is_dir():
        pytest.skip(
            f"no baseline fixtures at {BASELINE_FIXTURE_DIR}; generate them "
            "with src/pynwb/tests/make_fixtures.py"
        )
    return BASELINE_FIXTURE_DIR
