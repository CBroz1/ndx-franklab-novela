"""Characterize namespace loading and class generation.

Guards the behavior of ``ndx_franklab_novela/__init__.py``: the namespace is
loaded from the bundled spec, every documented type is generated by
``get_class``, and the ndx-optogenetics dependency is pulled in as a side
effect of importing this package.
"""

import pytest
from pynwb import get_class

import ndx_franklab_novela
from ndx_franklab_novela import (
    AssociatedFiles,
    CameraDevice,
    DataAcqDevice,
    FrankLabOptogeneticEpochsTable,
    HeaderDevice,
    NwbElectrodeGroup,
    Probe,
    Shank,
    ShanksElectrode,
)

NAMESPACE = "ndx-franklab-novela"

EXPECTED_TYPES = {
    "AssociatedFiles": AssociatedFiles,
    "CameraDevice": CameraDevice,
    "DataAcqDevice": DataAcqDevice,
    "FrankLabOptogeneticEpochsTable": FrankLabOptogeneticEpochsTable,
    "HeaderDevice": HeaderDevice,
    "NwbElectrodeGroup": NwbElectrodeGroup,
    "Probe": Probe,
    "Shank": Shank,
    "ShanksElectrode": ShanksElectrode,
}


def test_all_lists_every_exported_type():
    """``__all__`` matches the set of types the package documents."""
    assert set(ndx_franklab_novela.__all__) == set(EXPECTED_TYPES)


@pytest.mark.parametrize("type_name", sorted(EXPECTED_TYPES))
def test_type_is_accessible_at_package_level(type_name):
    """Each name in ``__all__`` resolves to a class on the package.

    Parameters
    ----------
    type_name : str
        Neurodata type name.
    """
    attribute = getattr(ndx_franklab_novela, type_name)
    assert isinstance(attribute, type)
    assert attribute is EXPECTED_TYPES[type_name]


@pytest.mark.parametrize("type_name", sorted(EXPECTED_TYPES))
def test_type_is_registered_in_namespace(type_name):
    """``get_class`` returns the same class the package exposes.

    Parameters
    ----------
    type_name : str
        Neurodata type name.

    Notes
    -----
    This is the check that fails loudly if the namespace stops loading or if
    class generation starts returning fresh classes on each call, which would
    silently break ``isinstance`` checks in downstream code such as spyglass.
    """
    assert get_class(type_name, NAMESPACE) is EXPECTED_TYPES[type_name]


def test_optogenetics_dependency_is_loaded():
    """Importing this package also loads the ndx-optogenetics namespace.

    ``FrankLabOptogeneticEpochsTable`` extends ``OptogeneticEpochsTable``, so
    the dependency must be registered for the type to resolve at all.
    """
    import sys

    assert "ndx_optogenetics" in sys.modules
    assert get_class("OptogeneticEpochsTable", "ndx-optogenetics") is not None


def test_namespace_helpers_are_not_left_in_package_namespace():
    """The import-time helpers are deleted after use.

    ``__init__.py`` explicitly deletes these names; keeping them would make
    ``from ndx_franklab_novela import *`` leak pynwb internals.
    """
    for name in ("load_namespaces", "get_class", "files", "os"):
        assert not hasattr(ndx_franklab_novela, name)
